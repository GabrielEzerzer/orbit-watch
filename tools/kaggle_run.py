"""Run a command on Kaggle CPU against the exact commit at HEAD, and fetch what it wrote.

    python tools/kaggle_run.py [--slug ow-suite] [-- <command...>]      (default: pytest -q)

The committed tree (``git archive HEAD``) is embedded in a private Kaggle script kernel with its
commit SHA. On Kaggle the kernel unpacks it, runs ``pip install -e .[dev]`` and the command, and
writes COMMIT.txt, run.log (stdout and stderr together), exit_code.txt and anything the command
put under /kaggle/working/out. This script waits for the kernel, downloads those files to
data/kaggle/<slug>/out, checks COMMIT.txt against the pushed SHA, prints the end of run.log and
exits with the command's exit code.
"""

from __future__ import annotations

import argparse
import base64
import json
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

OWNER = "gabrielezerzer"  # the Kaggle account the authenticated CLI pushes to
REPO = Path(__file__).resolve().parents[1]
SLUG_RE = re.compile(r"[a-z0-9][a-z0-9-]{4,49}")  # Kaggle wants titles of at least 5 characters
POLL_SECONDS = 30
# shortcut: one fixed limit, under Kaggle's 12 h session cap so the outputs still get written; make
# it an argument if a job ever needs a different one.
COMMAND_TIMEOUT_SECONDS = 11 * 3600
WAIT_LIMIT_SECONDS = 13 * 3600
ACTIVE = {"queued", "running"}
TERMINAL = {"complete", "error", "cancelacknowledged"}

KERNEL_TEMPLATE = '''\
"""orbit-watch run of commit {sha}, generated by tools/kaggle_run.py. Kaggle runs it as a script."""
import base64, io, os, subprocess, sys, tarfile

COMMIT = {sha!r}
COMMAND = {command!r}
TIMEOUT = {timeout!r}
ARCHIVE_B64 = {archive!r}

WORK = "/kaggle/working"
SRC = "/tmp/orbit-watch-src"  # outside /kaggle/working, so the source is not part of the output


def run(argv, log):
    log.write("$ " + " ".join(argv) + "\\n")
    log.flush()
    try:
        return subprocess.run(argv, cwd=SRC, stdout=log, stderr=subprocess.STDOUT, timeout=TIMEOUT).returncode
    except subprocess.TimeoutExpired:
        log.write(f"\\ntimed out after {{TIMEOUT}} s\\n")
        return 124


def main():
    os.makedirs(os.path.join(WORK, "out"), exist_ok=True)
    with open(os.path.join(WORK, "COMMIT.txt"), "w") as f:
        f.write(COMMIT + "\\n")
    os.makedirs(SRC, exist_ok=True)
    with tarfile.open(fileobj=io.BytesIO(base64.b64decode(ARCHIVE_B64)), mode="r:gz") as tar:
        # Our own commit's archive; the data filter where this Python has it.
        tar.extractall(SRC, **({{"filter": "data"}} if hasattr(tarfile, "data_filter") else {{}}))
    # The command's python and pytest are the interpreter pip installs into.
    argv = list(COMMAND)
    if argv[0] in ("python", "python3"):
        argv[0] = sys.executable
    elif argv[0] == "pytest":
        argv[:1] = [sys.executable, "-m", "pytest"]
    with open(os.path.join(WORK, "run.log"), "w") as log:
        code = run([sys.executable, "-m", "pip", "install", "-q", "-e", ".[dev]"], log)
        if code == 0:
            code = run(argv, log)
        else:
            log.write(f"\\npip install failed with exit code {{code}}; the command did not run\\n")
    with open(os.path.join(WORK, "exit_code.txt"), "w") as f:
        f.write(f"{{code}}\\n")
    with open(os.path.join(WORK, "run.log")) as log:
        print(log.read()[-4000:])
    print(f"exit code {{code}}")
    # The kernel itself always succeeds, so its outputs can be downloaded; the result is exit_code.txt.


if __name__ == "__main__":
    main()
'''


def build_kernel(archive: bytes, sha: str, command: list[str], slug: str) -> tuple[str, dict]:
    """The kernel script and its kernel-metadata.json for a gzipped tar of the tree at ``sha``."""
    if not SLUG_RE.fullmatch(slug):
        raise ValueError(f"slug must match {SLUG_RE.pattern}: {slug!r}")
    if not re.fullmatch(r"[0-9a-f]{40}", sha):
        raise ValueError(f"not a full commit SHA: {sha!r}")
    if not command:
        raise ValueError("empty command")
    # Git Bash turns a '/kaggle/working/out' argument into 'C:/Program Files/Git/kaggle/...'.
    converted = [a for a in command if re.match(r"[A-Za-z]:[/\\]", a)]
    if converted:
        raise ValueError(
            f"Windows path in the Kaggle command: {converted}; from Git Bash, set MSYS_NO_PATHCONV=1"
        )
    script = KERNEL_TEMPLATE.format(
        sha=sha,
        command=list(command),
        timeout=COMMAND_TIMEOUT_SECONDS,
        archive=base64.b64encode(archive).decode("ascii"),
    )
    metadata = {
        "id": f"{OWNER}/{slug}",
        "title": slug,
        "code_file": f"{slug}.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": False,
        "enable_tpu": False,
        "enable_internet": True,  # pip install needs PyPI
        "dataset_sources": [],
        "competition_sources": [],
        "kernel_sources": [],
        "model_sources": [],
    }
    return script, metadata


def git(*args: str) -> bytes:
    return subprocess.run(["git", *args], cwd=REPO, check=True, capture_output=True).stdout


def kaggle(*args: str) -> str:
    done = subprocess.run(["kaggle", *args], capture_output=True, text=True)
    if done.returncode != 0:
        raise RuntimeError(f"kaggle {' '.join(args)} failed:\n{done.stdout}{done.stderr}")
    return done.stdout


def status(ref: str) -> str:
    """'queued', 'running', 'complete', 'error', ... from `kaggle kernels status`."""
    out = kaggle("kernels", "status", ref)
    match = re.search(r'status "(?:KernelWorkerStatus\.)?(\w+)"', out)
    if not match:
        raise RuntimeError(f"unexpected kaggle kernels status output: {out!r}")
    return match.group(1).lower().replace("_", "")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--slug", default="ow-suite")
    parser.add_argument("command", nargs="*", help="the command to run on Kaggle (after --)")
    args = parser.parse_args()
    command = args.command or ["pytest", "-q"]

    if git("status", "--porcelain").strip():
        sys.exit("the working tree is not clean; commit first so the run matches a commit")
    sha = git("rev-parse", "HEAD").decode().strip()
    script, metadata = build_kernel(
        git("archive", "--format=tar.gz", "HEAD"), sha, command, args.slug
    )

    base = REPO / "data" / "kaggle" / args.slug
    push, out = base / "push", base / "out"
    for d in (push, out):
        shutil.rmtree(d, ignore_errors=True)
    push.mkdir(parents=True)
    (push / metadata["code_file"]).write_text(script, encoding="utf-8", newline="\n")
    (push / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")

    ref = metadata["id"]
    print(f"pushing {sha[:12]} to {ref}: {' '.join(command)}")
    pushed = kaggle("kernels", "push", "-p", str(push)).strip()
    print(pushed)
    # The CLI exits 0 on some refusals, e.g. "Kernel push error: Maximum batch CPU session count".
    if "successfully pushed" not in pushed:
        sys.exit("kaggle kernels push did not report a successful push; nothing was run")
    print(f"https://www.kaggle.com/code/{ref}")

    # Right after a push the status can still be the previous version's; only a terminal status
    # seen after an active one (or long after the push) belongs to this run. COMMIT.txt confirms it.
    started, seen_active, last = time.monotonic(), False, None
    while True:
        state = status(ref)
        if state != last:
            print(f"{time.strftime('%H:%M:%S')} {state}", flush=True)
            last = state
        seen_active |= state in ACTIVE
        elapsed = time.monotonic() - started
        if state in TERMINAL and (seen_active or elapsed > 600):
            break
        if elapsed > WAIT_LIMIT_SECONDS:
            sys.exit(f"gave up waiting after {elapsed / 3600:.1f} h; status {state}")
        time.sleep(POLL_SECONDS)

    out.mkdir(parents=True)
    kaggle("kernels", "output", ref, "-p", str(out))
    commit_file, code_file = out / "COMMIT.txt", out / "exit_code.txt"
    if not commit_file.exists() or not code_file.exists():
        sys.exit(f"kernel ended {state} without COMMIT.txt and exit_code.txt; see {out}")
    got = commit_file.read_text().strip()
    if got != sha:
        sys.exit(f"COMMIT.txt says {got}, but {sha} was pushed")
    log = out / "run.log"
    if log.exists():
        print("\n".join(log.read_text(encoding="utf-8", errors="replace").splitlines()[-30:]))
    code = int(code_file.read_text().strip())
    print(f"commit {got}, exit code {code}, outputs in {out}")
    return code


if __name__ == "__main__":
    sys.exit(main())
