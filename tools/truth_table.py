# Write groundtruth/objects.md, one row per labelled object, from the label files and cached element sets.
# It never runs the detector, so it may list holdout objects.
# Burns are log rows (an IDS row can hold several burns); the ISS label files have no norad_id column.

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

from orbit_watch.spacetrack import CACHE_DIR
from orbit_watch.truth import GROUNDTRUTH, load_splits

SPAN = "2021-01-01--2026-01-01"


def burns_2021_2025(norad: int, files: list[str]) -> int:
    n = 0
    for name in files:
        with open(GROUNDTRUTH / name, encoding="utf-8", newline="") as f:
            for r in csv.DictReader(f):
                if "norad_id" in r and int(r["norad_id"]) != norad:
                    continue
                day = r.get("start_utc") or r["date_utc"]
                n += "2021" <= day[:4] <= "2025"
    return n


def table(tle_dir: Path) -> str:
    lines = ["# Labelled objects", "",
             "Generated by `python tools/truth_table.py` from `splits.json`, the ground-truth CSVs "
             f"and the cached Space-Track files (`gp_history-<id>-{SPAN}.json`). Do not edit by hand.",
             "", "| NORAD | Name | Regime | Split | Burns 2021-2025 | Element sets 2021-2025 |",
             "|---|---|---|---|---|---|"]
    for norad, o in sorted(load_splits().items(), key=lambda kv: (kv[1]["split"], kv[1]["regime"], kv[0])):
        path = tle_dir / f"gp_history-{norad}-{SPAN}.json"
        tles = len(json.loads(path.read_text(encoding="utf-8"))) if path.is_file() else "not cached"
        lines.append(f"| {norad} | {o['name']} | {o['regime']} | {o['split']} | "
                     f"{burns_2021_2025(norad, o['truth_files'])} | {tles} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Write groundtruth/objects.md: one row per labelled object, generated from the files.")
    p.add_argument("--tle-dir", type=Path, default=CACHE_DIR)
    args = p.parse_args(argv)
    text = table(args.tle_dir)
    (GROUNDTRUTH / "objects.md").write_text(text, encoding="utf-8", newline="\n")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
